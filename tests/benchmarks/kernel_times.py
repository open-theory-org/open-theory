#!/usr/bin/env python3
"""Kernel time of every registered check, at representative sizes.

Builds honest requests for each check of `formal/core/Checks/Registry.lean`, runs them through
`ot_kernel --stdin --time --compare` (both lanes must agree) and prints a table; `--write` saves it
to docs/benchmarks.md. Times are the kernel's own (`addDecl`), on this machine, best of three.

    python3 tests/benchmarks/kernel_times.py [--write]

Requires `lake build ot_kernel`.
"""
from __future__ import annotations

import hashlib
import platform
import random
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "methods" / "neural"))
from mlp_exact_certificate import certificate, random_network, request  # noqa: E402
from verifier.core import trees  # noqa: E402
from verifier.core.pool_rate import check_args, sample_args  # noqa: E402

KERNEL = ROOT / ".lake" / "build" / "bin" / "ot_kernel"
D = 20


def rtree(rng, k):
    if k == 0:
        return {"leaf": rng.gauss(0, 0.1)}
    return {"feature": rng.randrange(D), "threshold": rng.uniform(-3, 3), "low": rtree(rng, k - 1), "high": rtree(rng, k - 1)}


def mtree(rng, k, lo, hi):
    if k == 0:
        return {"leaf": rng.uniform(lo, hi)}
    if rng.random() < 0.4:
        mid = (lo + hi) / 2
        return {"feature": 0, "threshold": rng.uniform(-3, 3), "low": mtree(rng, k - 1, lo, mid), "high": mtree(rng, k - 1, mid, hi)}
    return {"feature": rng.randrange(1, D), "threshold": rng.uniform(-3, 3), "low": mtree(rng, k - 1, lo, hi), "high": mtree(rng, k - 1, lo, hi)}


def cases():
    rng = random.Random(1)
    out = []
    for dims in ([64, 16, 10], [784, 128, 10]):
        layers, x = random_network(dims, 8, rng)
        params = sum(a * b + b for a, b in zip(dims, dims[1:]))
        out.append(("mlp-exact", f"ReLU MLP {'-'.join(map(str, dims))} ({params:,} parameters)", request(certificate(layers, x, 8))))
    for n in (1000, 20000):
        bits = [rng.random() < 0.05 for _ in range(n)]
        out.append(("pool-witness", f"pool rate, {n:,} sampled bits", " ".join(check_args(bits, (sum(bits), 1, 10, (1, 2)), 1000))))
    for n in (1000, 5000, 20000):
        blocks = [int.from_bytes(hashlib.sha256(i.to_bytes(8, "big")).digest(), "big") for i in range(n)]
        pairs = [("approve" if rng.random() < 0.9 else "decline", "approve") for _ in range(n)]
        fails = sum(a != b for a, b in pairs)
        out.append(("pool-sample-witness", f"pool rate from the beacon, {n:,} items",
                    " ".join(sample_args(blocks, 100000, pairs, False, (fails, 1, 5, (1, 2)), 1000))))
    for n, depth in ((10, 5), (100, 5), (500, 5)):
        model = {"base": 0, "trees": [rtree(rng, depth) for _ in range(n)]}
        x0 = [rng.uniform(-3, 3) for _ in range(D)]
        box = {str(f): [x0[f], x0[f]] for f in range(D)}
        box["0"] = [x0[0] - 0.05, x0[0] + 0.05]
        s, kl, kf = trees.scale(model)
        B = trees.scale_box(box, kf)
        from fractions import Fraction
        tau = Fraction(sum(trees.reach(t, B, min) for t in s["trees"]), 2 ** kl)
        req, _ = trees.robust_request(model, box, True, tau)
        out.append(("tree-robust", f"{n} trees of depth {depth}, small box", "tree-robust " + " ".join(map(str, req))))
        mm = {"base": 0, "trees": [mtree(rng, depth, -1, 1) for _ in range(n)]}
        req, _ = trees.monotone_request(mm, 0, True)
        out.append(("tree-monotone", f"{n} trees of depth {depth}, all inputs", "tree-monotone " + " ".join(map(str, req))))
    return out


def fmt(us: float) -> str:
    return f"{us / 1000:.2f} ms" if us < 1e6 else f"{us / 1e6:.2f} s"


def main() -> int:
    rows = cases()
    best = [float("inf")] * len(rows)
    for _ in range(3):
        text = "".join(r[2] + "\n" for r in rows)
        out = subprocess.run([str(KERNEL), "--stdin", "--time", "--compare"], input=text, capture_output=True, text=True)
        if out.returncode != 0:
            print(f"[FAIL] ot_kernel exited {out.returncode}: {out.stderr[-500:]}")
            return 1
        if out.stdout.split() != ["true"] * len(rows):
            print(f"[FAIL] some honest request was rejected: {out.stdout.split()}")
            return 1
        times = [float(m) for m in re.findall(r"kernel ([0-9.]+) µs", out.stderr)]
        best = [min(b, t) for b, t in zip(best, times)]
    lines = ["| Check | Request | Kernel time |", "| --- | --- | --- |"]
    lines += [f"| `{c}` | {what} | {fmt(t)} |" for (c, what, _), t in zip(rows, best)]
    table = "\n".join(lines)
    print(table)
    if "--write" in sys.argv:
        (ROOT / "docs/benchmarks.md").write_text(
            "# Kernel time of every check\n\n"
            "Generated by `python3 tests/benchmarks/kernel_times.py --write`: honest requests, both lanes agreeing,\n"
            f"best of three, on {platform.machine()} {platform.system()}. The kernel lane is the `verified` one\n"
            "([trust.md](trust.md)); the compiled lane is not timed here.\n\n"
            + table + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
