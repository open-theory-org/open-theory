#!/usr/bin/env python3
"""The map of formal/core: which modules the claim types rest on, and which are library or research.

Reads the imports of every module of formal/core and computes, for each, the claim-type modules
that depend on it (transitively). A module is

  claim       on the import path of a claim type (Specs/ClaimTypes.lean), a fast check
              (Checks/Registry.lean, Specs/PoolSample.lean) or a Lean name of a catalog method
              (its spec, check and correctness theorems): a certificate's meaning rests on it
  library     not on that path: a formal result tracked in the blueprint, not yet behind any claim

Writes docs/architecture/core-map.md; fails when it is stale.

    python3 tests/regression/check_core_map.py [--write]
"""
from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORE = ROOT / "formal" / "core"
OUT = ROOT / "docs" / "architecture" / "core-map.md"
LAYERS = ["Checks", "Foundations", "Models", "Properties", "Theory", "Scopes", "Specs"]
# the modules whose meaning a certificate has: claim types, the checks the kernel runs, and the
# correctness theorems that join them
ROOTS = {"Specs.ClaimTypes": "claim types", "Checks.Registry": "fast checks", "Specs.PoolSample": "kernel-checked sample"}


def modules() -> dict[str, tuple[Path, list[str]]]:
    out = {}
    for p in sorted(CORE.rglob("*.lean")):
        name = ".".join(p.relative_to(CORE).with_suffix("").parts)
        imports = re.findall(r"^import\s+(\S+)", p.read_text(encoding="utf-8"), re.M)
        out[name] = (p, [i for i in imports if i.split(".")[0] in LAYERS])
    return out


def closure(mods, root) -> set[str]:
    seen, stack = set(), [root]
    while stack:
        m = stack.pop()
        if m in seen or m not in mods:
            continue
        seen.add(m)
        stack += mods[m][1]
    return seen


def method_modules(mods) -> set[str]:
    """The modules declaring a Lean name of some catalog method."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from check_lean_decls import declared_index
    index = declared_index()
    out = set()
    for p in (ROOT / "catalog" / "methods").glob("*.toml"):
        lean = tomllib.loads(p.read_text()).get("lean", {})
        for n in lean.get("spec", []) + lean.get("check", []) + lean.get("correctness", []):
            path = index.get(n)
            if path and CORE in path.parents:
                out.add(".".join(path.relative_to(CORE).with_suffix("").parts))
    return out


def render(mods) -> str:
    used = {r: closure(mods, r) for r in ROOTS}
    used["methods"] = set().union(*(closure(mods, m) for m in method_modules(mods)))
    on_path = set().union(*used.values())
    lines_of = {m: sum(1 for _ in p.open(encoding="utf-8")) for m, (p, _) in mods.items()}
    out = [
        "# Map of formal/core",
        "",
        "Generated by `python3 tests/regression/check_core_map.py --write`. **claim**: on the import path",
        "of a claim type (`Specs/ClaimTypes.lean`), of the fast checks (`Checks/Registry.lean`), of the",
        "kernel-checked sample (`Specs/PoolSample.lean`) or of a catalog method's Lean names: a",
        "certificate's meaning rests on it. **library**:",
        "a formal result tracked in the blueprint, not yet behind any claim type; it carries no assurance",
        "level ([../trust.md](../trust.md)).",
        "",
        "| Layer | Modules | Lines | claim | library |",
        "| --- | --- | --- | --- | --- |",
    ]
    for layer in LAYERS:
        ms = [m for m in mods if m.split(".")[0] == layer]
        claim = [m for m in ms if m in on_path]
        out.append(f"| {layer} | {len(ms)} | {sum(lines_of[m] for m in ms):,} | "
                   f"{len(claim)} ({sum(lines_of[m] for m in claim):,} lines) | {len(ms) - len(claim)} |")
    out += ["", "## Modules", "", "| Module | Lines | Status | Behind |", "| --- | --- | --- | --- |"]
    for m in sorted(mods, key=lambda m: (LAYERS.index(m.split('.')[0]), m)):
        behind = ", ".join(v for r, v in {**ROOTS, "methods": "catalog methods"}.items() if m in used[r])
        out.append(f"| `{m}` | {lines_of[m]} | {'claim' if m in on_path else 'library'} | {behind or '—'} |")
    return "\n".join(out) + "\n"


def main() -> int:
    mods = modules()
    missing = [r for r in ROOTS if r not in mods]
    if missing:
        print(f"[FAIL] roots not found: {missing}")
        return 1
    fresh = render(mods)
    if "--write" in sys.argv:
        OUT.write_text(fresh, encoding="utf-8")
    elif not OUT.exists() or OUT.read_text(encoding="utf-8") != fresh:
        print("[FAIL] docs/architecture/core-map.md is stale: run tests/regression/check_core_map.py --write")
        return 1
    on = sum(1 for l in fresh.splitlines() if "| claim |" in l)
    print(f"[OK] core map current: {on} of {len(mods)} modules are behind a certificate (claim types, checks, methods)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
