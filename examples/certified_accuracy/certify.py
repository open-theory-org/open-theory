#!/usr/bin/env python3
"""Unforgeable generalization bound: demo.

A vendor claims: "my network's error on new data is at most p, with 95% confidence."
This script turns the claim into a Lean file in which the Lean kernel itself
  1. re-runs the network on every held-out example (exact integer arithmetic),
  2. re-counts the errors,
  3. checks the exact binomial tail inequality behind the bound,
and the resulting theorem is a theorem about the population error. Nothing is trusted
except the Lean kernel and the assumption that the held-out rows are IID and were not
used for training.

Usage:
  certify.py                         honest claim (tightest bound), should PASS
  certify.py --claim-errors 10       lie about the error count, should FAIL
  certify.py --claim-bound 0.03      claim a tighter bound than the data supports, should FAIL
  certify.py --tamper-label 5        change one held-out label (keep the claim), should FAIL
  certify.py --tamper-weight 100     change one network weight (keep the claim), should FAIL
"""
import argparse
import json
import subprocess
import sys
import time
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "methods" / "statistical"))
from pacbayes_mlp_certificate import error_count, parameter_count, validate  # noqa: E402
import binomial_bound  # noqa: E402

ARTIFACT = ROOT / "examples/certified_accuracy/model/pacbayes_digits64.json"
OUT = Path(__file__).resolve().parent / "out"
SCALE = 10_000          # bounds are stated in basis points
BATCH = 20
DELTA_DEN = 20          # confidence 1 - 1/20 = 95%


def tightest_bound(n, k):
    """Tightest bound the kernel will accept, in units of 1 / SCALE."""
    return binomial_bound.tightest_bound(n, k, SCALE, DELTA_DEN)


def lean_file(model, rows, batch_claims, k, a):
    n = len(rows)
    parts = [f"""import Verification.Statistical.QuantizedMLPPACBayes
import Verification.Statistical.BinomialTail

/-! Generated by examples/certified_accuracy/certify.py. Every number below is re-checked by the
Lean kernel (`decide +kernel`): the network is re-run on each held-out row. -/

set_option maxRecDepth 100000

namespace DemoCert
open MeasureTheory StatLean.StatisticalLearning OpenTheory OpenTheory.QuantizedMLP OpenTheory.BinomialTail

def arch : Arch := ⟨{model['inputs']}, {model['hidden']}, {model['classes']}, {model['hidden_bias_scale']}, {model['output_bias_scale']}⟩

def networkCodes : List ℕ := {model['codes']}

theorem networkCodes_length : networkCodes.length = arch.parameterCount := by decide +kernel

def network : Code arch.parameterCount 4 := codeOfList _ networkCodes
"""]
    names = []
    for i in range(0, n, BATCH):
        name = f"batch{i // BATCH:02d}"
        names.append(name)
        body = ",\n  ".join(f"({r[:-1]}, {r[-1]})" for r in rows[i:i + BATCH])
        parts.append(f"""
def {name} : List Observation := [
  {body}]

theorem {name}_errors : errorCount arch network {name} = {batch_claims[i // BATCH]} := by
  rw [network, errorCount_codeOfList _ _ networkCodes_length]
  decide +kernel
""")
    parts.append(f"""
def heldoutRows : List Observation := {" ++ ".join(names)}

theorem heldoutRows_length : heldoutRows.length = {n} := by decide +kernel

theorem heldout_errors : errorCount arch network heldoutRows = {k} := by
  simp only [heldoutRows, errorCount_append, {", ".join(nm + "_errors" for nm in names)}]

def heldoutSample : Fin {n} → Observation :=
  fun i => heldoutRows.get (Fin.cast heldoutRows_length.symm i)

theorem heldout_empirical_error :
    empRisk (classificationLoss arch) heldoutSample network = ({k} / {n} : ℝ) := by
  unfold heldoutSample
  rw [empiricalRisk_eq_errorCount_cast arch network heldoutRows heldoutRows_length, heldout_errors]
  norm_num

theorem loss01 (z : Observation) :
    classificationLoss arch network z = 0 ∨ classificationLoss arch network z = 1 := by
  unfold classificationLoss errorBit errorBitOfWeights
  split <;> simp

/-- The exact binomial tail: `{DELTA_DEN} · {SCALE}^{n} · P(Bin({n}, {a}/{SCALE}) ≤ {k}) ≤ {SCALE}^{n}`. -/
theorem tail_le : {DELTA_DEN} * tailNumerator {n} {k} {a} {SCALE} ≤ {SCALE} ^ {n} := by decide +kernel

theorem binomCdf_le : binomCdf {n} {k} ({a} / {SCALE}) ≤ 1 / {DELTA_DEN} := by
  have h := (Nat.cast_le (α := ℝ)).2 tail_le
  rw [Nat.cast_mul, Nat.cast_pow] at h
  have hp : ({a} / {SCALE} : ℝ) = (({a} : ℕ) : ℝ) / (({SCALE} : ℕ) : ℝ) := by norm_num
  rw [hp, binomCdf_div_eq _ _ (by norm_num) (by norm_num), div_le_iff₀ (by positivity)]
  generalize (({SCALE} : ℕ) : ℝ) ^ {n} = B at h ⊢
  push_cast at h
  linarith

/-- **Certificate.** With probability ≥ 95% over {n} IID held-out examples, the event
"at most {k} held-out errors AND population error above {a / SCALE:.2%}" has probability ≤ 5%. -/
theorem certificate (P : Population Observation) :
    sampleLaw P.law {n} {{s | empRisk (classificationLoss arch) s network ≤ ({k} / {n} : ℝ) ∧
      ({a} / {SCALE} : ℝ) < P.risk (classificationLoss arch network)}} ≤ ENNReal.ofReal (1 / {DELTA_DEN}) :=
  testSet_bound (k := {k}) loss01 (classificationLoss_measurable arch network)
    (by norm_num) (by norm_num) binomCdf_le

/-- The realized held-out sample satisfies the first condition, so the certificate
says: unless we are in the 5% bad event, the population error is at most {a / SCALE:.2%}. -/
theorem realized_sample_fails_iff (P : Population Observation) :
    heldoutSample ∈ {{s | empRisk (classificationLoss arch) s network ≤ ({k} / {n} : ℝ) ∧
      ({a} / {SCALE} : ℝ) < P.risk (classificationLoss arch network)}} ↔
      ({a} / {SCALE} : ℝ) < P.risk (classificationLoss arch network) := by
  simp [heldout_empirical_error]

end DemoCert
""")
    return "".join(parts)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--claim-errors", type=int, help="claimed number of held-out errors (default: true count)")
    ap.add_argument("--claim-bound", type=float, help="claimed error bound, e.g. 0.05 (default: tightest valid)")
    ap.add_argument("--tamper-label", type=int, help="index of a held-out row whose label is changed")
    ap.add_argument("--tamper-weight", type=int, help="index of a network code that is changed")
    args = ap.parse_args()

    art = json.loads(ARTIFACT.read_text())
    model, rows = dict(art["model"]), [list(r) for r in art["heldout_rows"]]
    validate(model)
    n = len(rows)
    true_batches = [error_count(model, rows[i:i + BATCH]) for i in range(0, n, BATCH)]
    true_k = sum(true_batches)

    # the vendor's claim is computed on the untampered artifact
    k = true_k if args.claim_errors is None else args.claim_errors
    a = tightest_bound(n, true_k) if args.claim_bound is None else round(args.claim_bound * SCALE)
    claims = list(true_batches)
    if k != true_k:                      # spread the lie over the batches
        diff = k - true_k
        for j in range(len(claims)):
            step = max(diff, -claims[j]) if diff < 0 else diff
            claims[j] += step; diff -= step
            if diff == 0:
                break

    # tampering happens after the claim was made
    if args.tamper_label is not None:
        r = rows[args.tamper_label]
        r[-1] = (r[-1] + 1) % 10
    if args.tamper_weight is not None:
        codes = list(model["codes"]); codes[args.tamper_weight] = (codes[args.tamper_weight] + 1) % 4
        model["codes"] = codes

    OUT.mkdir(exist_ok=True)
    tag = "".join(f"_{k}{v}" for k, v in (("errors", args.claim_errors), ("bound", args.claim_bound),
                  ("label", args.tamper_label), ("weight", args.tamper_weight)) if v is not None)
    path = OUT / f"Cert{tag.replace('.', 'p')}.lean"
    path.write_text(lean_file(model, rows, claims, k, a))
    print(f"network: {model['inputs']}-{model['hidden']}-{model['classes']}, {parameter_count(model)} parameters")
    print(f"held-out examples: {n}, true errors: {true_k}, tightest valid bound: "
          f"{tightest_bound(n, true_k) / SCALE:.2%} at 95% confidence")
    print(f"CLAIM: {k} errors, population error ≤ {a / SCALE:.2%} (95%)"
          + ("   [held-out label tampered]" if args.tamper_label is not None else "")
          + ("   [network weight tampered]" if args.tamper_weight is not None else ""))
    print("Lean kernel checking...", flush=True)
    t0 = time.time()
    res = subprocess.run(["lake", "env", "lean", str(path)], cwd=ROOT, capture_output=True, text=True)
    dt = time.time() - t0
    out = (res.stdout + res.stderr).splitlines()
    errs = [i for i, l in enumerate(out) if ": error" in l]
    if res.returncode == 0 and not errs:
        print(f"\n  ACCEPTED in {dt:.0f}s: theorem DemoCert.certificate is proved.")
        print(f"  With 95% confidence, population error ≤ {a / SCALE:.2%}. Checked by the Lean kernel.")
        return
    print(f"\n  REJECTED in {dt:.0f}s. The Lean kernel refused the certificate:")
    shown = 0
    for i in errs:
        body = " ".join(x.strip() for x in out[i + 1:i + 3])
        if "errorCountOfWeights" in body:
            batch = next((t for t in body.split() if t.startswith("batch")), "a batch")
            j = int(batch[5:]) if batch[5:].isdigit() else None
            rows_ = f"held-out rows {j * BATCH}-{min((j + 1) * BATCH, n) - 1}" if j is not None else batch
            print(f"    - the kernel re-ran the network on {rows_}: the claimed error count is false")
        elif "tailNumerator" in body:
            print(f"    - the data do not support a bound of {a / SCALE:.2%}: "
                  f"P(Bin({n}, {a / SCALE:.4f}) ≤ {k}) > 5%, so the binomial tail inequality is false")
        else:
            print("    -", out[i].split(".lean:")[-1][:150])
        shown += 1
        if shown == 3:
            break
    sys.exit(1)


if __name__ == "__main__":
    main()
